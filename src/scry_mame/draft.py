"""`gfx_draft`: a `gfx.yaml` DRAFT derived from this session's evidence, and the report beside it.

WHAT GOES IN. Only what the evidence (`evidence`) establishes, each entry with its status and
source: FORMATS, ASSETS per source and bank a written format decodes, and a COMMAND per
capture whose words `correlate` proved to hold a located object's x and y. Nothing is
guessed: what the evidence cannot settle is listed in `not_proved` and in the report.

WHEN A LAYOUT IS PROVED on a source (a region or share at an offset). A `gfx_locate` match's window
has to vary along BOTH axes (a line decodes the same under every layout that differs along the
other axis), and then it proves its layout in one of two ways. BY SHAPE: its rarest pen covers at
least the tile's longer side (a dot is found by chance among hundreds of tiles). BY UNIQUENESS, for
a layout of `UNIQUE_PLANES_MIN` planes or more and a window whose rarest pen still covers half
the longer side: it is its layout's one match in an answer that searched every tile of the block
(a window of many pens says more than its rarest pen covers, and chance would match it elsewhere
too). The argument is only as strong as the search is wide, and the caller sets the width: a
search cut to one window matches once whenever it matches at all, so neither the windows tried nor
the tiles searched can say how strong it was. The rarest pen can: the pixels that tell one tile
from another are what a unique match rests on, and a pen shared by every tile of a font (a row
gradient) tells nothing apart. The evidence keeps each match's `compared` beside its shape.
Either way,
no other source matched a window overlapping it on the same frame (a pixel has one origin, and a
letter drawn from one block can be found by chance in another's tiles). Layouts of different tile
sizes are not rivals, since one block is often decoded both ways (8x8 chars and 16x16 sprites), and
each is proved on its own matches. Layouts of the SAME size that both matched there are rivals: one
is proved only when some answer tried both and it matched a window the other did not; a rival never
told apart that way is ambiguous and not written. A person's pick from a sweep's sheet is `human`
where nothing of its size is proved, promoted when a match proves the same layout, and named as
contradicted when a match proves another.

WHAT STAYS OUT OF IT. Every figure: the matches, the banks, the pairing counts, the hypotheses,
live in the REPORT, JSON written by this tool and regenerated byte for byte from the same
evidence, and the draft's `source` strings name the report's key instead of repeating a number.

NEVER OVER A MANIFEST. The draft's first line is the manifest's DRAFT marker, and a file that
exists without it is refused, so a confirmed manifest is never overwritten; the owner confirms a
draft by deleting that line. The draft is read back by the loader before the reply: one it
refuses is a defect here.
"""

