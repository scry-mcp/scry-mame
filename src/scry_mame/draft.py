MARKER = manifest.DRAFT_MARKER
REPORT_BY = "gfx_draft"
DRAFT_NAME = "gfx-draft.yaml"
BY_MAX = 80
NOT_PROVED_SHOWN = 8
AXES_MIN = 2            # distinct rows, and distinct columns, a window needs to prove a layout
UNIQUE_PLANES_MIN = 3   # below it a pixel holds at most four values: the art proof by shape is for
UNIQUE_RAREST_DIVISOR = 2  # uniqueness proves a window whose rarest pen covers side/this
# why a window proved nothing, by the word the report counts it under
CAUSES = {
    "rows": "it does not vary from row to row",
    "cols": "it does not vary from column to column",
    "rarest": "its rarest pen covers less than the tile's longer side",
    "not_unique": "its layout matched more than once in the answer",
    "partial_search": "its layout's search left tiles of the block untried",
}
UNPROVING_WHY = (
    "a `flat` window proved nothing and overlapped no other source's match; `causes` counts the "
    "flat ones by what they failed: " + "; ".join(f"`{w}`, {why}" for w, why in CAUSES.items())
    + f" (the last two named only at {UNIQUE_PLANES_MIN} planes or more, for a window that "
    "varies along both axes); a `contested` window overlaps another source's match on the same "
    "frame, and a pixel has one origin")
_HEX_KEYS = ("address", "mask", "value")

Key = tuple[Any, ...]


# ------------------------------------------------------------------ the arguments

def report_path(dest: Path) -> Path:
    return dest.with_name(dest.name[:-len(".yaml")] + ".report.json")


def check_gfx_draft(dest: str = "", choose: Any = None, **_: Any) -> None:
    """`gfx_draft`'s machine-independent half: the paths' shape and the choice's."""
    if dest:
        inputs.writable_path("dest", dest)
    if dest and not dest.endswith(".yaml"):
        raise st.Invalid("bad_argument", f"dest={dest!r}: a `.yaml` file, or empty for the "
                         "scratch's")
    if choose is None:
        return
    if not isinstance(choose, dict) or sorted(choose) != ["candidate", "chosen_by"]:
        raise st.Invalid("bad_argument", 'choose is {"candidate": "<a sweep id, s1c3>", '
                         '"chosen_by": "<who chose>"}, both, and nothing else')
    cand, by = choose["candidate"], choose["chosen_by"]
    if not isinstance(cand, str) or evidence.SWEEP_ID.match(cand) is None:
        raise st.Invalid("bad_argument", f"choose.candidate={cand!r} is a sweep candidate's id, "
                         "as its sheet labels it (`s1c3`)")
    # printable, so the YAML reader takes it back whole: it refuses a tab, and splits a line at
    # any of the separators `str.splitlines` knows, which are all unprintable
    if (not isinstance(by, str) or not by.strip() or len(by) > BY_MAX
            or not by.isprintable() or any(c in by for c in "\"\\")):
        raise st.Invalid("bad_argument", f"choose.chosen_by={by!r} names who chose, on one line "
                         f"of at most {BY_MAX} printable characters, with no quote or backslash")


def _refuse_foreign(dest: Path, report: Path) -> None:
    """A draft is written only over a draft, and a report only over a report; a link, a
    directory, or a file this cannot read, where either goes is refused naming it: replacing a
    link would drop it, and following it would write where the caller never named."""
    for path in (dest, report):
        if path.is_symlink():
            raise st.Invalid("bad_argument", f"{path} is a link, where gfx_draft writes a file: "
                             "name another `dest`")
        if path.is_dir():
            raise st.Invalid("bad_argument", f"{path} is a directory, where gfx_draft writes a "
                             "file: name another `dest`")
    if dest.exists():
        try:
            first = dest.read_text(encoding="utf-8", errors="replace").split("\n", 1)[0]
        except OSError as e:
            raise st.Invalid("bad_argument", f"{dest} exists and cannot be read ({e.strerror}), "
                             "so whether it is a draft cannot be told: name another `dest`"
                             ) from None
        if first != MARKER:
            raise st.Invalid("bad_argument", f"{dest} exists and its first line is not the DRAFT "
                             "marker: it is a manifest, and gfx_draft never overwrites one. Name "
                             "another `dest`", marker=MARKER)
    if report.exists():
        try:
            by = json.loads(report.read_text(encoding="utf-8")).get("written_by")
        except (ValueError, AttributeError, OSError):
            by = None
        if by != REPORT_BY:
            raise st.Invalid("bad_argument", f"{report} exists and is not a report gfx_draft "
                             "wrote: name another `dest`")


# ------------------------------------------------------------------ the formats

def _candidate_index(loc: dict[str, Any], name: str) -> int:
    return next(i for i, c in enumerate(loc["candidates"]) if c["name"] == name)


def _layout_of(loc: dict[str, Any], name: str) -> dict[str, Any]:
    layout: dict[str, Any] = loc["candidates"][_candidate_index(loc, name)]
    return layout


def _yaml_layout(reply: dict[str, Any]) -> dict[str, Any]:
    return {k: reply[k] for k in ("width", "height", "planes", "planeoffset", "xoffset",
                                  "yoffset", "charincrement")}


def _searched_whole(loc: dict[str, Any]) -> list[bool]:
    """Per candidate, whether the answer searched every tile of its block; False where the
    record does not say."""
    return list(loc.get("searched_whole", [False] * len(loc["candidates"])))


def _failed(match: dict[str, Any], loc: dict[str, Any]) -> set[str]:
    """The `CAUSES` a match's window failed in its answer `loc`: empty when it proves its layout,
    by shape or by uniqueness (the module's paragraph)."""
    k = _candidate_index(loc, match["layout"])
    layout = loc["candidates"][k]
    rows, cols, rarest = (int(v) for v in match["shape"])
    flat_axes = {word for word, ok in (("rows", rows >= AXES_MIN), ("cols", cols >= AXES_MIN))
                 if not ok}
    by_shape = flat_axes | ({"rarest"} if rarest < max(layout["width"], layout["height"])
                            else set())
    # uniqueness stands in for the rarest pen only down to half the longer side (the module's
    # paragraph)
    side = max(layout["width"], layout["height"])
    if (not by_shape or flat_axes or layout["planes"] < UNIQUE_PLANES_MIN
            or rarest * UNIQUE_RAREST_DIVISOR < side):
        return by_shape
    # a cut answer kept only some of its matches, so it can say no layout matched once
    once = (loc["matches_total"] == len(loc["matches"])
            and sum(m["layout"] == match["layout"] for m in loc["matches"]) == 1)
    by_uniqueness = ((set() if once else {"not_unique"})
                     | (set() if _searched_whole(loc)[k] else {"partial_search"}))
    return by_shape | by_uniqueness if by_uniqueness else set()


class _Found:
    """One layout's matches on one source, by answer."""

    def __init__(self, layout: dict[str, Any], palette: str) -> None:
        self.layout, self.palette = layout, palette
        self.windows: dict[int, set[tuple[int, int]]] = {}    # answer -> every window matched
        self.strong: dict[int, set[tuple[int, int]]] = {}     # answer -> windows that prove
        self.tiles: set[int] = set()
        self.bases: set[int] = set()
        self.weak = 0
        self.causes: dict[str, int] = {}      # a word of `CAUSES` -> the weak windows failing it
        self.contested = 0

    def add(self, n: int, m: dict[str, Any], contested: bool, failed: set[str]) -> None:
        """Answer `n`'s match `m`, and the `CAUSES` it failed (`_failed`) unless `contested`."""
        win = (m["window"][0], m["window"][1])
        self.windows.setdefault(n, set()).add(win)
        if contested:
            self.contested += 1
            return
        if not failed:
            self.strong.setdefault(n, set()).add(win)
            self.tiles.add(m["tile"])
            if m["base"] is not None:          # a pen map's match proves no bank
                self.bases.add(m["base"])
            return
        self.weak += 1
        for word in failed:
            self.causes[word] = self.causes.get(word, 0) + 1

    @property
    def size(self) -> tuple[int, int]:
        return self.layout["width"], self.layout["height"]


Tried = dict[int, set[Key]]      # answer -> the layouts it tried over every tile they have;
                                 # absent when its matches were cut
CELL = 32                        # the side of the squares matched rectangles are indexed by


def _told_apart(a: _Found, b: _Found, tried: Tried, ka: Key, kb: Key) -> bool:
    """Whether some answer that tried both, and kept every match, saw `a` prove a window where
    `b` matched nothing: a cut answer may have dropped the very match of `b` that says otherwise."""
    return any(n in tried and ka in tried[n] and kb in tried[n] and wins - b.windows.get(n, set())
               for n, wins in a.strong.items())


def _cells(frame: int, x: int, y: int, w: int, h: int) -> list[tuple[int, int, int]]:
    return [(frame, cx, cy) for cx in range(x // CELL, (x + w - 1) // CELL + 1)
            for cy in range(y // CELL, (y + h - 1) // CELL + 1)]


def _gather() -> tuple[dict[evidence.SourceKey, dict[Key, _Found]], Tried]:
    found: dict[evidence.SourceKey, dict[Key, _Found]] = {}
    tried: Tried = {}
    # every matched rectangle, indexed by the squares of its frame it covers, with its source:
    # a pixel has one origin, and the index keeps a match from being checked against every other
    drawn: dict[tuple[int, int, int], list[tuple[evidence.SourceKey, int, int, int, int]]] = {}
    for loc in evidence.locates():
        src = evidence.SourceKey.of(loc["source"])
        for m in loc["matches"]:
            lay = _layout_of(loc, m["layout"])
            rect = (src, *m["window"], lay["width"], lay["height"])
            for cell in _cells(loc["frame_screen"], *rect[1:]):
                drawn.setdefault(cell, []).append(rect)
    for loc in evidence.locates():
        if loc["matches_total"] == len(loc["matches"]):
            tried[loc["n"]] = {evidence.layout_key(c)
                               for c, all_tiles in zip(loc["candidates"], _searched_whole(loc),
                                                       strict=True)
                               if all_tiles}
        src = evidence.SourceKey.of(loc["source"])
        for m in loc["matches"]:
            reply = _layout_of(loc, m["layout"])
            f = found.setdefault(src, {}).setdefault(evidence.layout_key(reply),
                                                     _Found(reply, loc["palette"]))
            x, y = m["window"]
            w, h = reply["width"], reply["height"]
            contested = any(o != src and x < ox + ow and ox < x + w and y < oy + oh and oy < y + h
                            for cell in _cells(loc["frame_screen"], x, y, w, h)
                            for o, ox, oy, ow, oh in drawn[cell])
            f.add(loc["n"], m, contested, set() if contested else _failed(m, loc))
    return found, tried


def _verdicts(found: dict[Key, _Found], tried: Tried
              ) -> tuple[dict[Key, _Found], dict[Key, list[Key]]]:
    """The layouts proved on one source, and those left ambiguous with the rivals they were
    never told apart from."""
    proved: dict[Key, _Found] = {}
    ambiguous: dict[Key, list[Key]] = {}
    for key, f in found.items():
        if not f.strong:
            continue
        rivals = [k for k, o in found.items() if k != key and o.strong and o.size == f.size]
        untold = [k for k in rivals if not _told_apart(f, found[k], tried, key, k)]
        if untold:
            ambiguous[key] = untold
        else:
            proved[key] = f
    return proved, ambiguous


def _unique(taken: dict[str, Any], base: str) -> str:
    """`base` as a key the strict reader takes, suffixed until no entry holds it."""
    name, k = mame_yaml.key(base), 2
    while name in taken:
        name, k = f"{mame_yaml.key(base)}_{k}", k + 1
    return name


class _Draft:
    """The draft's sections and the report's, built together so each source names its key."""

    def __init__(self, report_name: str) -> None:
        self.report_name = report_name
        self.formats: dict[str, dict[str, Any]] = {}
        self.assets: dict[str, dict[str, Any]] = {}
        self.commands: dict[str, dict[str, Any]] = {}
        self.report: dict[str, Any] = {"formats": {}, "assets": {}, "ambiguous": [],
                                       "unproving": [], "correlations": []}
        self.not_proved: list[str] = []
        self.keys: dict[Key, str] = {}                            # layout -> format name
        self.written: dict[tuple[evidence.SourceKey, Key], list[str]] = {}    # its assets

    def cite(self, section: str, name: str) -> str:
        return f"evidence in {self.report_name}, {section}.{name}"

    def name_format(self, key: Key, reply: dict[str, Any]) -> str:
        """Named by its shape, since two blocks may share one layout."""
        if key not in self.keys:
            self.keys[key] = _unique(
                self.formats, f"tiles_{reply['width']}x{reply['height']}x{reply['planes']}")
        return self.keys[key]


def _latest_choices() -> dict[tuple[evidence.SourceKey, tuple[int, int]], dict[str, Any]]:
    """A later choice for the same source and tile size replaces an earlier one."""
    out: dict[tuple[evidence.SourceKey, tuple[int, int]], dict[str, Any]] = {}
    for ch in evidence.choices():
        size = (ch["resolved"]["width"], ch["resolved"]["height"])
        out[(evidence.SourceKey.of(ch["source"]), size)] = ch
    return out


Plan = tuple[Key, dict[str, Any], str, "_Found | None", "dict[str, Any] | None"]


def _formats(d: _Draft) -> None:
    found, tried = _gather()
    choices = _latest_choices()
    for src in sorted(set(found) | {s for s, _ in choices}):
        here = found.get(src, {})
        proved, ambiguous = _verdicts(here, tried)
        for f in here.values():
            if f.weak or f.contested:
                d.report["unproving"].append({
                    "source": src.reply(), "layout": f.layout["name"],
                    "flat": f.weak, "causes": dict(sorted(f.causes.items())),
                    "contested": f.contested, "why": UNPROVING_WHY})
            if not f.strong:
                d.not_proved.append(f"{src.tag}: {f.layout['name']} matched only windows that "
                                    f"prove no layout ({_unproved_how(f)})")
        for key, rivals in ambiguous.items():
            d.report["ambiguous"].append({
                "source": src.reply(), "layout": here[key].layout,
                "not_told_apart_from": [here[k].layout["name"] for k in rivals]})
            d.not_proved.append(f"{src.tag}: {here[key].layout['name']} was never told apart from "
                                f"{[here[k].layout['name'] for k in rivals]}")
        plans: list[Plan] = [(key, f.layout, "proved", f, choices.get((src, f.size)))
                             for key, f in sorted(proved.items(), key=lambda kv: kv[1].size)]
        sizes = {f.size for f in proved.values()}
        for (csrc, size), choice in sorted(choices.items(), key=lambda kv: str(kv[0])):
            if csrc != src or size in sizes:
                continue
            if choice["key"] in ambiguous:
                d.not_proved.append(f"{src.tag}: {choice['candidate']} is written as a person's "
                                    "choice among layouts the screen could not tell apart")
            plans.append((choice["key"], choice["resolved"], "human", None, choice))
        for plan in plans:
            _write_format(d, src, plan, several=len(plans) > 1)


def _unproved_how(f: _Found) -> str:
    """Why a layout's windows proved nothing, in words: the conditions the flat ones failed and
    whether another block matched too."""
    how = [f"failed: {', '.join(sorted(f.causes))}"] if f.causes else []
    if f.contested:
        how.append("matched from another block too")
    return "; ".join(how)


def _write_format(d: _Draft, src: evidence.SourceKey, plan: Plan, several: bool) -> None:
    key, layout, status, f, choice = plan
    name = d.name_format(key, layout)
    entry: dict[str, Any] = {"status": status, "source": src.reply(),
                             "layout": layout, "choice": None}
    if choice is not None:
        entry["choice"] = {k: choice[k] for k in ("candidate", "chosen_by", "sweep", "sheet")}
    tag = st.bare_tag(src.tag)
    if f is not None:
        entry.update(proved_by=sorted(f.strong), tiles=sorted(f.tiles), bases=sorted(f.bases),
                     palette=f.palette)
        why = f"gfx_locate matched it on the screen on {tag}, told apart from every rival"
        if choice is not None and choice["key"] == key:
            why += f", confirming the choice of {choice['chosen_by']} ({choice['candidate']})"
        elif choice is not None:
            entry["contradicted_choice"] = True
            d.not_proved.append(f"{src.tag}: the choice {choice['candidate']} was contradicted "
                                "by a match with another layout")
        text = _yaml_layout(layout)
    else:
        assert choice is not None
        why = (f"chosen by {choice['chosen_by']} from gfx_sweep s{choice['sweep']}'s sheet sha256 "
               f"{choice['sheet'][:16]}")
        text = dict(choice["raw"])
    if name not in d.formats:
        d.formats[name] = {"layout": text, "status": status,
                           "source": f"{why}; {d.cite('formats', name)}"}
    d.report["formats"].setdefault(name, []).append(entry)
    if src.kind in ("region", "share"):
        _assets(d, src, key, name, layout, f, choice, several)


def _assets(d: _Draft, src: evidence.SourceKey, key: Key, fmt: str, layout: dict[str, Any],
            f: _Found | None, choice: dict[str, Any] | None, several: bool) -> None:
    """One asset per bank the proving matches drew with (the chosen sweep's own pens for a
    choice), when the palette is a device's; named after its tag, with its tile size when the
    tag holds several formats and its bank when the format was drawn through several."""
    if f is not None and not f.bases:
        d.not_proved.append(f"{src.tag}: no asset for {fmt}: its matches read the screen through "
                            "a pen map, which proves the format and never the pens it is drawn "
                            "through")
        return
    if f is not None:
        palette, bases, status = f.palette, sorted(f.bases), "proved"
    elif choice is not None:
        palette, bases, status = choice["palette"], [choice["pen_base"]], "human"
    else:
        return
    if not palette or palette == "none":
        d.not_proved.append(f"{src.tag}: no asset for {fmt}, chosen under no palette")
        return
    tag = st.bare_tag(src.tag)
    stem = f"{tag}_{layout['width']}x{layout['height']}" if several else tag
    names = d.written.setdefault((src, key), [])
    for base in bases:
        name = f"{stem}_pen{base}" if len(bases) > 1 else stem
        if mame_yaml.key(name) in d.assets and src.offset:
            name = f"{name}_at{src.offset:x}"       # the same tag at another offset
        name = _unique(d.assets, name)
        asset: dict[str, Any] = {"format": fmt, "tag": tag, "palette": st.bare_tag(palette)}
        if src.offset:
            asset["offset"] = src.offset
        if base:
            asset["pen_base"] = base
        asset.update(status=status, source=("the matches that prove its format were drawn "
                                            "through these pens" if f is not None else
                                            "the pens of the sheet it was chosen from")
                     + f"; {d.cite('assets', name)}")
        d.assets[name] = asset
        d.report["assets"][name] = {"source": src.reply(), "format": fmt,
                                    "pen_base": base}
        names.append(name)


# ------------------------------------------------------------------ the commands

def _events() -> dict[tuple[evidence.SourceKey, Key], list[corr.Event]]:
    """The answers whose every match sits in one window of one layout, grouped by source and
    layout: the object's place is known, and its tile when one tile matched there."""
    groups: dict[tuple[evidence.SourceKey, Key], list[corr.Event]] = {}
    for loc in evidence.locates():
        ms = loc["matches"]
        if (not ms or loc["matches_total"] != len(ms)
                or len({(m["layout"], *m["window"]) for m in ms}) != 1):
            continue
        tiles = {m["tile"] for m in ms}
        key = (evidence.SourceKey.of(loc["source"]),
               evidence.layout_key(_layout_of(loc, ms[0]["layout"])))
        groups.setdefault(key, []).append(corr.Event(
            loc["n"], loc["frame_screen"], ms[0]["window"][0], ms[0]["window"][1],
            tiles.pop() if len(tiles) == 1 else None))
    return groups


def _captures() -> list[tuple[Any, dict[str, Any], dict[str, Any]]]:
    """Every installed capture with its header; one not installed has no files of its own."""
    out = []
    for owner, rec in sorted(capture.block_captures(), key=lambda kv: str(kv[1].get("tally_id"))):
        if STATE.scratch is None or not mtap.answered(STATE.scratch, rec):
            continue
        try:
            head = capture.parse_capture_header(Path(rec["path"]).read_text(encoding="utf-8",
                                                                     errors="replace"))
        except OSError:
            head = None
        out.append((owner, rec, head or {}))
    return out


def _field(h: dict[str, Any], d: _Draft, cmd: str) -> dict[str, Any]:
    field: dict[str, Any] = {"parts": [{"word": h["word"], "mask": int(h["mask"], 16)}]}
    if h["add"]:
        field["add"] = h["add"]
    if h["sign"] == -1:
        field["sign"] = -1
    field.update(status="proved", source=("it agrees with the located object on every paired "
                                          f"event; {d.cite('commands', cmd)}"))
    return field


def _commands(d: _Draft) -> None:
    """Each capture against each group of events; a command where x and y are proved."""
    groups = _events()
    for owner, rec, head in _captures():
        word_bytes = max(head.get("data_width", 8) // 8, 1)
        if rec["width"] % word_bytes:
            word_bytes = 1
        order = head.get("endianness", "little")
        # each row's fire value as the reader compares it (`capture.lane`): None where the
        # write left part of the fire word unwritten
        rows = [(row.frame, row.block, capture.lane(row.data, row.mask,
                                                    head.get("data_width", 8), order,
                                                    rec["trigger"], word_bytes))
                for row in capture.rows(Path(rec["rows_path"]))]
        by_frame = corr.frames([(f, b) for f, b, _ in rows], word_bytes, order)
        cap = {"tally_id": rec["tally_id"], "addr": st.hex_addr(rec["addr"]),
               "length": rec["width"], "trigger_addr": st.hex_addr(rec["trigger"]),
               "cpu": owner[1],
               "rows_kept": len(rows),
               "word_bytes": word_bytes, "endianness": head.get("endianness")}
        if (errors := callbacks.reply(head)) is not None:
            cap["callback_errors"] = errors
        for (src, lkey), events in sorted(groups.items(), key=lambda kv: str(kv[0])):
            if len(events) < corr.MIN_PAIRED:
                continue
            res = corr.correlate(by_frame, events, word_bytes, rec["width"] // word_bytes)
            entry = {"capture": cap, "group": {"source": src.reply(),
                                               "format": d.keys.get(lkey)},
                     **res, "command": None}
            d.report["correlations"].append(entry)
            f = res["fields"]
            if not all(f.get(r, {}).get("status") == "proved" for r in ("dest_x", "dest_y")):
                d.not_proved.append(f"capture {rec['tally_id']} against {st.bare_tag(src.tag)}: "
                                    + res.get("why", "dest_x and dest_y are not both proved"))
                continue
            # rows its tap never kept are writes nothing paired, so no command is proved from it
            if raised := callbacks.said(errors, "its"):
                d.not_proved.append(f"capture {rec['tally_id']} against {st.bare_tag(src.tag)}: "
                                    f"{raised}, so its rows are short of the writes")
                continue
            name = f"write_{rec['trigger']:x}"
            if name in d.commands:
                name = f"{name}_{st.bare_tag(src.tag)}"
            name = entry["command"] = _unique(d.commands, name)
            d.not_proved += [elsewhere_reason(name, role, field, res["lag"])
                             for role, field in f.items() if "elsewhere" in field]
            assets = d.written.get((src, lkey), [])
            d.commands[name] = _command(d, name, rec, owner, word_bytes, rows, f, lkey,
                                        assets[0] if len(assets) == 1 else "")


def elsewhere_reason(command: str, role: str, field: dict[str, Any], lag: int) -> str:
    """Why a role that holds at another lag is not in the command: nothing held it at the
    group's lag, or several things did."""
    lags = sorted({h["lag"] for h in field["elsewhere"]})
    how = ("holds only at lag" if field["status"] == "none" else
           f"is ambiguous at lag {lag} and also holds at lag")
    return (f"{command}: {role} {how} {lags}, the lag of dest_x and dest_y being {lag}; see the "
            "report")


def _command(d: _Draft, name: str, rec: dict[str, Any], owner: Any, word_bytes: int,
             rows: list[tuple[int, bytes, int | None]], f: dict[str, Any], lkey: Key,
             asset: str) -> dict[str, Any]:
    trigger, addr = rec["trigger"], rec["addr"]
    values = {value for _, _, value in rows}
    one = values.pop() if len(values) == 1 and len(rows) > 1 else None
    fire: dict[str, Any] = {}
    inside = addr <= trigger < addr + rec["width"] and (trigger - addr) % word_bytes == 0
    if inside and one is not None:
        fire.update(word=(trigger - addr) // word_bytes, value=one)
    else:
        fire["address"] = trigger
        if one is not None:
            fire["value"] = one
    fire.update(status="proved", source=f"every row the correlation paired was a write to it; "
                f"{d.cite('commands', name)}")
    block: dict[str, Any] = {"address": addr, "words": rec["width"] // word_bytes,
                             "word_bytes": word_bytes}
    if owner[1]:
        block["cpu"] = st.bare_tag(owner[1])
    block.update(status="proved", source=f"the capture the correlation read; "
                 f"{d.cite('commands', name)}")
    fields = {r: _field(f[r], d, name) for r in ("dest_x", "dest_y", "source_tile")
              if f.get(r, {}).get("status") == "proved"}
    size = f"the located layout's tile size; {d.cite('commands', name)}"
    fields["width"] = {"const": lkey[0], "status": "proved", "source": size}
    fields["height"] = {"const": lkey[1], "status": "proved", "source": size}
    out: dict[str, Any] = {"block": block, "fire": fire}
    if asset:
        out["asset"] = asset
    out["fields"] = fields
    return out


# ------------------------------------------------------------------ the writer

def render(system: str, d: _Draft) -> str:
    doc: dict[str, Any] = {"schema": manifest.SCHEMA, "systems": [system]}
    for name, section in (("formats", d.formats), ("assets", d.assets),
                          ("commands", d.commands)):
        if section:
            doc[name] = section
    head = [MARKER.removeprefix("# "), f"evidence: {d.report_name}. Every entry names what "
            "proved it; the figures live in the report."]
    return mame_yaml.dumps(doc, head, _HEX_KEYS)


# ------------------------------------------------------------------ the tool

def _choose(choose: dict[str, Any]) -> tuple[dict[str, Any], bool]:
    """The choice's record, and whether it is new: the same person's same pick is ONE choice
    however many times it is made."""
    found = evidence.find_candidate(choose["candidate"])
    if found is None:
        evidence.candidate_layout(choose["candidate"], "choose.candidate")   # the refusal
        raise AssertionError("unreachable")
    sweep, cand = found
    record = {"candidate": cand["id"], "chosen_by": choose["chosen_by"], "sweep": sweep["n"],
              "sheet": sweep["sheet"]["sha256"], "source": sweep["source"],
              "palette": sweep["palette"], "pen_base": sweep["pen_base"],
              "raw": cand["raw"], "resolved": cand["resolved"],
              "key": evidence.layout_key(cand["resolved"])}
    if record in evidence.choices():
        return record, False
    evidence.choices().append(record)
    return record, True


def _written(out: Path, report: Path) -> tuple[_Draft, str, str]:
    """The draft derived from the evidence, loaded back, and written with its report: the
    draft, its text and the report's."""
    if not evidence.locates() and not evidence.choices():
        raise st.Invalid("needs_call", "no evidence to draft from: this session has no "
                         "gfx_locate answer and no choice. Locate a screen patch (a sweep's "
                         "candidates by id) or choose from a sweep's sheet first")
    d = _Draft(report.name)
    _formats(d)
    _commands(d)
    text = render(STATE.system or "", d)
    try:
        manifest.parse(mame_yaml.loads(text), str(out), "")
    except (mame_yaml.YamlError, manifest.ManifestError) as e:
        raise st.Invalid("unexpected_answer", f"the draft this derived does not load: {e}. "
                         "That is a defect of gfx_draft", draft=text) from None
    body = {"written_by": REPORT_BY, "system": STATE.system, "draft": out.name,
            "evidence": {"locates": evidence.locates(), "sweeps": evidence.sweeps(),
                         "choices": [{k: v for k, v in c.items() if k != "key"}
                                     for c in evidence.choices()]},
            **d.report, "not_proved": d.not_proved}
    report_text = json.dumps(body, sort_keys=True, indent=1, default=list) + "\n"
    # A draft beside a missing or older report cites evidence that is not its own, so both are
    # written aside and put in place only once both were written: a failed write leaves neither.
    # The two renames that follow are not one act; only a rename failing between them splits it
    aside = [(path.with_name(path.name + ".tmp"), path, content)
             for path, content in ((report, report_text), (out, text))]
    try:
        for tmp, _, content in aside:
            tmp.write_text(content, encoding="utf-8", newline="")    # LF on every host
        for tmp, path, _ in aside:
            os.replace(tmp, path)
    except OSError as e:
        for tmp, _, _ in aside:
            with contextlib.suppress(OSError):        # under a file, there is nothing to remove
                tmp.unlink(missing_ok=True)
        raise st.Invalid("host_failed", f"{out} or its report {report.name} cannot be written "
                         f"({e.strerror or e}): name another `dest`") from None
    return d, text, report_text


def gfx_draft(scratch: Path, dest: str = "", choose: dict[str, Any] | None = None
              ) -> dict[str, Any]:
    """The body of the `gfx_draft` tool: the draft and its report from the evidence."""
    check_gfx_draft(dest, choose)
    out = inputs.writable_path("dest", dest) if dest else scratch / DRAFT_NAME
    report = report_path(out)
    _refuse_foreign(out, report)
    recorded, new = _choose(choose) if choose is not None else (None, False)
    try:
        d, text, report_text = _written(out, report)
    except BaseException:
        if new and recorded is not None:    # a draft that failed records no choice
            evidence.choices().remove(recorded)
        raise
    reply: dict[str, Any] = {
        "manifest": {"path": str(out), "sha256": hashlib.sha256(text.encode()).hexdigest()},
        "report": {"path": str(report),
                   "sha256": hashlib.sha256(report_text.encode()).hexdigest()},
        "formats": {n: f["status"] for n, f in d.formats.items()},
        "asset_names": sorted(d.assets),
        "command_fields": {n: sorted(c["fields"]) for n, c in d.commands.items()},
        "evidence": {"locates": len(evidence.locates()), "sweeps": len(evidence.sweeps()),
                     "choices": len(evidence.choices()),
                     "correlations": len(d.report["correlations"])},
        "not_proved": d.not_proved[:NOT_PROVED_SHOWN],
        "confirm": "the owner confirms the draft by deleting its first line; `gfx_load` loads "
                   "it before that and says `draft: true`",
    }
    if len(d.not_proved) > NOT_PROVED_SHOWN:
        reply["not_proved_more"] = len(d.not_proved) - NOT_PROVED_SHOWN
    if recorded is not None:
        reply["chose"] = {"candidate": recorded["candidate"], "chosen_by": recorded["chosen_by"]}
    return menvelope.envelope(reply)
